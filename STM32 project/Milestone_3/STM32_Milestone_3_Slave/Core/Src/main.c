/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_SPI1_Init();
  /* USER CODE BEGIN 2 */

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
      uint8_t dummy_rx[2] = {0};

      /* ---------------- Cycle 1 ---------------- */

      /* Receive Case ID from Master.
         NOTE: this call BLOCKS here until the Master starts clocking
         Cycle 1. That is what keeps the two sides synchronized: the
         Slave is guaranteed to be "parked" inside this call, ready,
         before any clock edges arrive. */
      HAL_SPI_TransmitReceive(
          &hspi1,
          dummy_rx,
          rx_data,
          2,
          HAL_MAX_DELAY
      );

      /* Convert received bytes to 16-bit ID */
      received_id = ((uint16_t)rx_data[0] << 8) | rx_data[1];

      /* Find matching case */
      voltage_x10 = 0;
      speed = 0;

      for (int i = 0; i < 5; i++)
      {
          if (cases[i].id == received_id)
          {
              voltage_x10 = cases[i].voltage_x10;
              speed = cases[i].speed;
              break;
          }
      }

      /* Pack Voltage + Speed into 24 bits */
      message_24bit = ((uint32_t)voltage_x10 << 12) | speed;

      /* Split into 3 bytes */
      tx_data[0] = (message_24bit >> 16) & 0xFF;
      tx_data[1] = (message_24bit >> 8) & 0xFF;
      tx_data[2] = message_24bit & 0xFF;

      /* ---------------- Cycle 2 ---------------- */

      uint8_t dummy_rx_3[3];


      HAL_SPI_TransmitReceive(
          &hspi1,
          tx_data,
          dummy_rx_3,
          3,
          HAL_MAX_DELAY
      );
  }
  /* USER CODE END 3 */
}

